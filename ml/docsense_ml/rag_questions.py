"""Generate eval/rag_questions.yaml from the demo pack (gold answers are exact by construction).

    python -m docsense_ml.rag_questions

Add your own questions by editing the YAML: each entry is
    id, category, question, gold_docs: [document names] | [], gold_contains: [strings the answer must
    contain] | [], answerable: true|false
"""

from __future__ import annotations

import json
from collections import defaultdict
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[2]


def doc_name(truth: dict, copy: bool = False) -> str:
    return f"{truth['vendor_name']} {truth['invoice_number']}" + (" (copy).jpg" if copy else ".jpg")


def money(v: float) -> str:
    return f"{v:,.2f}"


UNANSWERABLE = [
    "What is the warranty period for LED panels?",
    "Who is the chief executive of the vendor with the highest spend?",
    "What was the weather in Karachi on the day of the first invoice?",
    "What is the refund policy for returned goods?",
    "Which employee approved the largest invoice?",
    "What is the bank account number used to pay Al-Mart?",
]


def build(pack: Path, per_vendor: int = 1) -> list[dict]:
    rows = json.loads((pack / "manifest.json").read_text(encoding="utf-8"))
    by_vendor: dict[str, list[dict]] = defaultdict(list)
    for r in rows:
        if r["planted"] != "exact_dup" and not r["extracted_total_wrong"]:
            by_vendor[r["truth"]["vendor_name"]].append(r)
    qs: list[dict] = []

    def add(category, question, docs, contains, answerable=True):
        qs.append({"id": f"q{len(qs) + 1:03d}", "category": category, "question": question,
                   "gold_docs": docs, "gold_contains": contains, "answerable": answerable})  # fmt: skip

    for vendor, docs in sorted(by_vendor.items()):
        for r in docs[1 : 1 + per_vendor + 1]:  # a couple of invoices per vendor, not the first
            t = r["truth"]
            name = doc_name(t)
            add(
                "lookup_total",
                f"What was the total of invoice {t['invoice_number']} from {vendor}?",
                [name],
                [money(t["total"])],
            )
            add(
                "lookup_date",
                f"On what date was invoice {t['invoice_number']} from {vendor} issued?",
                [name],
                [t["invoice_date"]],
            )
        first = docs[1]["truth"]
        item = first["line_items"][0]
        add("line_item", f"What was the amount for {item['description']} on invoice {first['invoice_number']} from {vendor}?",
            [doc_name(first)], [f"{item['amount']:,.2f}"])  # fmt: skip
        ntn_docs = [doc_name(d["truth"]) for d in docs]
        add(
            "registration",
            f"What is the NTN of {vendor}?",
            ntn_docs,
            [first["ntn"].replace("-", "")[:7]],
        )
    for q in UNANSWERABLE:
        add("unanswerable", q, [], [], answerable=False)
    return qs


def main() -> None:
    pack = ROOT / "seed" / "demo_workspace"
    qs = build(pack)
    out = ROOT / "eval" / "rag_questions.yaml"
    out.parent.mkdir(exist_ok=True)
    header = "# Generated by `python -m docsense_ml.rag_questions`; extend by hand.\n"
    out.write_text(
        header + yaml.safe_dump({"questions": qs}, sort_keys=False, allow_unicode=True),
        encoding="utf-8",
    )
    cats = defaultdict(int)
    for q in qs:
        cats[q["category"]] += 1
    print(len(qs), "questions", dict(cats), "->", out)


if __name__ == "__main__":
    main()
