"""Render docs/eval-results/*.json into markdown tables and splice them into README.md.

    python scripts/readme_tables.py            # rewrites the block between the markers
    python scripts/readme_tables.py --check    # exit 1 if README is out of date (CI-friendly)

Markers in README.md:  <!-- results:start -->  ...  <!-- results:end -->
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
START, END = "<!-- results:start -->", "<!-- results:end -->"
CLASSES = ["vendor", "meta", "table", "totals", "other"]


def pct(v, digits: int = 1) -> str:
    return "n/a" if v is None else f"{v * 100:.{digits}f}%"


def load(results_dir: Path) -> list[dict]:
    runs = []
    for p in sorted(results_dir.glob("*.json")):
        d = json.loads(p.read_text(encoding="utf-8"))
        d["_file"] = p.name
        runs.append(d)
    return runs


def layout_table(runs: list[dict]) -> str:
    by_exp: dict[str, dict] = {}
    for r in runs:
        if r.get("kind") != "layout":
            continue
        exp = r["arm"].split(":")[0]
        by_exp.setdefault(exp, {"desc": r["arm"].split(": ", 1)[-1]})[r["dataset"]] = r["metrics"]
    if not by_exp:
        return "_No layout runs yet._"
    rows = [
        "| Experiment | Synthetic (hard) mAP@50 | Real CORD mAP@50 | real: table | real: totals |",
        "|---|---|---|---|---|",
    ]
    for exp in sorted(by_exp):
        e = by_exp[exp]
        syn, real = e.get("synthetic-hard", {}), e.get("cord-real-test", {})
        rp = real.get("per_class_ap50", {})
        rows.append(
            f"| **{exp}**: {e['desc']} | {pct(syn.get('map50'))} | **{pct(real.get('map50'))}** | "
            f"{pct(rp.get('table'))} | {pct(rp.get('totals'))} |"
        )
    detail = [
        "",
        "Per-class AP@50 on the synthetic hard set (60 images, all five classes):",
        "",
        "| Experiment | " + " | ".join(CLASSES) + " |",
        "|---|" + "---|" * len(CLASSES),
    ]
    for exp in sorted(by_exp):
        pc = by_exp[exp].get("synthetic-hard", {}).get("per_class_ap50", {})
        detail.append(f"| {exp} | " + " | ".join(pct(pc.get(c)) for c in CLASSES) + " |")
    return "\n".join(rows + detail)


def extraction_table(runs: list[dict]) -> str:
    rows = [r for r in runs if r.get("kind") == "extraction"]
    if not rows:
        return "_No extraction runs yet._"
    out = [
        "| Dataset | Arm | N | Micro F1 | Total exact-match | line-item F1 |",
        "|---|---|---|---|---|---|",
    ]
    for r in rows:
        m = r["metrics"]
        li = (m.get("line_items") or {}).get("f1")
        out.append(
            f"| {r['dataset']} | {r['arm']} | {r['n']} | {pct(m['micro']['f1'])} | "
            f"{pct(m.get('total_exact_match'))} | {pct(li)} |"
        )
    pf = next((r for r in rows if r["dataset"].startswith("cord")), None)
    if pf and pf["metrics"].get("per_field"):
        out += ["", "Per-field (CORD, " + pf["arm"] + "):", "", "| Field | Precision | Recall | F1 | Support |", "|---|---|---|---|---|"]
        for name, f in pf["metrics"]["per_field"].items():
            out.append(f"| {name} | {pct(f['precision'])} | {pct(f['recall'])} | {pct(f['f1'])} | {f['support']} |")
    return "\n".join(out)


def rag_table(runs: list[dict]) -> str:
    rows = [r for r in runs if r.get("kind") == "rag"]
    if not rows:
        return "_No RAG runs yet._"
    out = [
        "| Setup | Questions | Hit@5 | MRR | Unanswerable rejected by retrieval gate | Judge (1-5) | Citation accuracy | Abstention accuracy |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for r in rows:
        m = r["metrics"]
        a = m.get("answers") or {}
        out.append(
            f"| {r['arm']} | {r['n']} | {pct(m.get('hit_at_5'))} | {m.get('mrr', 'n/a')} | "
            f"{pct(m.get('unanswerable_rejected_by_gate'))} | {a.get('judge_score_mean_1_5', 'pending (needs API keys)')} | "
            f"{pct(a.get('citation_accuracy')) if a else 'pending'} | {pct(a.get('abstention_accuracy')) if a else 'pending'} |"
        )
    return "\n".join(out)


def render(results_dir: Path) -> str:
    runs = load(results_dir)
    return "\n".join(
        [
            START,
            "",
            "#### Layout model (mAP@50, IoU 0.5)",
            "",
            layout_table(runs),
            "",
            "#### Field extraction (OCR + extractor)",
            "",
            extraction_table(runs),
            "",
            "#### Ask your documents (RAG)",
            "",
            rag_table(runs),
            "",
            "_Generated by `python scripts/readme_tables.py` from `docs/eval-results/*.json`._",
            END,
        ]
    )


def splice(readme: str, block: str) -> str:
    if START not in readme or END not in readme:
        raise SystemExit(f"README.md needs the markers {START} ... {END}")
    return re.sub(re.escape(START) + r".*?" + re.escape(END), lambda _m: block, readme, flags=re.S)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--readme", default=str(ROOT / "README.md"))
    ap.add_argument("--results", default=str(ROOT / "docs" / "eval-results"))
    a = ap.parse_args()
    path = Path(a.readme)
    old = path.read_text(encoding="utf-8")
    new = splice(old, render(Path(a.results)))
    if a.check:
        return 0 if new == old else 1
    path.write_text(new, encoding="utf-8")
    print("README results tables updated")
    return 0


if __name__ == "__main__":
    sys.exit(main())
